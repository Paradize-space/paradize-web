/**
 * Compiles every Maizzle template in emails/ into lib/emails/generated.ts,
 * the only email content the server code can send.
 *
 * It runs before `next dev`, `next build` and `tsc` (see package.json), so
 * the output is never stale and never edited by hand. The file is not
 * committed. To change an email, change its .vue template.
 *
 * Each template must set `subject` and `from` (the sender's display name)
 * with `defineConfig()` and carry a <Plaintext> part; the build fails
 * rather than ship an email without them.
 *
 * Templates write images as paths into public/ ("/email/mark.png"), which
 * the preview server serves locally. Here every relative src and href gets
 * SITE_URL in front, because a mail app loads them from the live site, and
 * the build fails if one is still relative afterwards.
 *
 * Everyone who gets an email is on the mailing list, so every template
 * must link UNSUBSCRIBE_MARKER from both its HTML and its text part.
 * sendEmail() swaps the marker for the recipient's own token.
 *
 * Text inside [[double brackets]] is a placeholder still to be written.
 * With --strict (what `npm run build` uses) a placeholder fails the build,
 * so one can never be deployed; otherwise it is only reported, so
 * `npm run dev` keeps working while a draft is in progress.
 */
import { glob, mkdir, writeFile } from "node:fs/promises";
import { basename, dirname, relative } from "node:path";

import { createMaizzle, resolveConfig } from "@maizzle/framework";

const OUTPUT = "lib/emails/generated.ts";
const STRICT = process.argv.includes("--strict");
const PLACEHOLDER = /\[\[[^\]]*\]\]/g;
// The same address as SITE_URL in lib/site.ts.
const SITE_URL = "https://paradize.space";
const RELATIVE_URL = /\s(?:src|href)="(?!https:\/\/|mailto:)([^"]*)"/g;
const UNSUBSCRIBE_MARKER = "__UNSUBSCRIBE_TOKEN__";

const config = await resolveConfig();
// Set here and not in maizzle.config.ts, which the preview server also
// reads: there the images must keep coming from public/.
config.url = { ...config.url, base: SITE_URL };

const files = [];
for (const pattern of config.content) {
  for await (const file of glob(pattern)) files.push(file);
}
files.sort();

if (files.length === 0) {
  throw new Error(`No email templates match ${config.content.join(", ")}.`);
}

const maizzle = await createMaizzle(config);
const emails = {};
const unfinished = [];

try {
  for (const file of files) {
    const name = basename(file, ".vue");
    const where = relative(process.cwd(), file);
    const { html, plaintext, config: used } = await maizzle.render(file);

    for (const key of ["subject", "from"]) {
      if (typeof used[key] !== "string" || used[key].trim() === "") {
        throw new Error(`${where}: set ${key} with defineConfig({ ${key} }).`);
      }
    }
    if (!plaintext || plaintext.trim() === "") {
      throw new Error(`${where}: add a <Plaintext> part.`);
    }
    for (const [part, body] of [["HTML", html], ["text", plaintext]]) {
      if (!body.includes(`/unsubscribe?t=${UNSUBSCRIBE_MARKER}`)) {
        throw new Error(
          `${where}: the ${part} part needs an unsubscribe link, https://paradize.space/unsubscribe?t=${UNSUBSCRIBE_MARKER}.`,
        );
      }
    }
    const unreachable = [...html.matchAll(RELATIVE_URL)].map((m) => m[1]);
    if (unreachable.length) {
      throw new Error(
        `${where}: these URLs would not load in a mail app: ${unreachable.join(", ")}`,
      );
    }

    const placeholders = [
      ...new Set(`${used.subject}\n${html}\n${plaintext}`.match(PLACEHOLDER)),
    ];
    if (placeholders.length) unfinished.push(`${where}: ${placeholders.join(", ")}`);

    emails[name] = {
      subject: used.subject,
      from: used.from,
      html,
      text: plaintext,
    };
  }
} finally {
  await maizzle.close();
}

if (unfinished.length) {
  const report = `Emails with placeholders still to write:\n  ${unfinished.join("\n  ")}`;
  if (STRICT) throw new Error(report);
  console.warn(`emails: ${report}`);
}

const source = `// GENERATED by scripts/build-emails.mjs from the Maizzle templates in
// emails/. Do not edit: it is rebuilt before every dev, build and
// typecheck run, and it is not committed. Change the .vue template.

export const emails = ${JSON.stringify(emails, null, 2)} as const satisfies Record<
  string,
  { subject: string; from: string; html: string; text: string }
>;

export type EmailName = keyof typeof emails;

/** In every email's unsubscribe link, until sendEmail() fills it in. */
export const UNSUBSCRIBE_MARKER = ${JSON.stringify(UNSUBSCRIBE_MARKER)};
`;

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, source);

console.log(
  `emails: compiled ${Object.keys(emails).join(", ")} into ${OUTPUT}`,
);
